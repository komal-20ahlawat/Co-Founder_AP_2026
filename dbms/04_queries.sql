-- =========================================================
-- 1. AUTHENTICATION
-- Source: controllers/authController.js
-- =========================================================

-- R1 | READ | Check whether an email is already registered (signup).
SELECT id
FROM users
WHERE email = $1;

-- W1 | WRITE | Create the user account.
-- $1 = normalized email
-- $2 = password hash generated by bcrypt in the backend
INSERT INTO users (email, password_hash)
VALUES ($1, $2)
RETURNING id, email, created_at;

-- W2 | WRITE | Create the user's initial profile after signup.
-- $1 = newly created user id
-- $2 = user's name
INSERT INTO profiles (user_id, full_name)
VALUES ($1, $2);

-- R2 | READ | Fetch account details for login.
-- The backend compares the submitted password with password_hash using bcrypt.
SELECT
    u.id,
    u.email,
    u.password_hash,
    p.full_name
FROM users u
JOIN profiles p ON u.id = p.user_id
WHERE u.email = $1;

-- R3 | READ | Fetch the logged-in user's details (/auth/me).
-- $1 = authenticated user's id from the JWT
SELECT
    u.id,
    u.email,
    u.email_verified,
    p.full_name,
    p.profile_picture,
    p.headline,
    p.bio,
    p.education,
    p.experience,
    p.github_url,
    p.portfolio_url,
    p.availability,
    p.collaboration_preferences
FROM users u
JOIN profiles p ON u.id = p.user_id
WHERE u.id = $1;


-- =========================================================
-- 2. USER PROFILE
-- Source: controllers/profileController.js
-- =========================================================

-- R4 | READ | Get the logged-in user's profile.
-- $1 = authenticated user's id
SELECT
    u.id,
    u.email,
    p.full_name,
    p.profile_picture,
    p.headline,
    p.bio,
    p.education,
    p.experience,
    p.github_url,
    p.portfolio_url,
    p.availability,
    p.collaboration_preferences
FROM users u
JOIN profiles p ON u.id = p.user_id
WHERE u.id = $1;

-- W3 | WRITE | Update the logged-in user's profile.
-- $1-$8 = profile fields; $9 = authenticated user's id
UPDATE profiles
SET
    full_name = $1,
    headline = $2,
    bio = $3,
    education = $4,
    experience = $5,
    github_url = $6,
    portfolio_url = $7,
    availability = $8,
    updated_at = CURRENT_TIMESTAMP
WHERE user_id = $9
RETURNING *;


-- =========================================================
-- 3. SKILLS
-- Source: controllers/skillController.js
-- =========================================================

-- R5 | READ | Get all available skills.
SELECT id, name
FROM skills
ORDER BY name ASC;

-- R6 | READ | Get skills selected by the logged-in user.
-- $1 = authenticated user's id
SELECT s.id, s.name
FROM skills s
JOIN user_skills us ON s.id = us.skill_id
WHERE us.user_id = $1
ORDER BY s.name ASC;

-- W4 | WRITE | Insert a skill if it does not exist, or return the existing skill.
-- $1 = skill name
INSERT INTO skills (name)
VALUES ($1)
ON CONFLICT (name)
DO UPDATE SET name = EXCLUDED.name
RETURNING id, name;

-- W5 | WRITE | Link the skill to the logged-in user.
-- $1 = user id; $2 = skill id
INSERT INTO user_skills (user_id, skill_id)
VALUES ($1, $2)
ON CONFLICT (user_id, skill_id) DO NOTHING;

-- W6 | WRITE | Remove a skill from the logged-in user's profile.
-- $1 = user id; $2 = skill id
DELETE FROM user_skills
WHERE user_id = $1 AND skill_id = $2
RETURNING skill_id;

-- =========================================================
-- 4. INTERESTS
-- Source: controllers/interestController.js
-- =========================================================

-- R7 | READ | Get all available interests.
SELECT id, name
FROM interests
ORDER BY name ASC;

-- R8 | READ | Get interests selected by the logged-in user.
-- $1 = authenticated user's id
SELECT i.id, i.name
FROM user_interests ui
JOIN interests i ON i.id = ui.interest_id
WHERE ui.user_id = $1
ORDER BY i.name ASC;

-- W7 | WRITE | Insert an interest if it does not exist, or return the existing one.
-- $1 = interest name
INSERT INTO interests (name)
VALUES ($1)
ON CONFLICT (name)
DO UPDATE SET name = EXCLUDED.name
RETURNING id, name;

-- W8 | WRITE | Link the interest to the logged-in user.
-- $1 = user id; $2 = interest id
INSERT INTO user_interests (user_id, interest_id)
VALUES ($1, $2)
ON CONFLICT (user_id, interest_id) DO NOTHING;

-- W9 | WRITE | Remove an interest from the logged-in user's profile.
-- $1 = user id; $2 = interest id
DELETE FROM user_interests
WHERE user_id = $1 AND interest_id = $2
RETURNING interest_id;


-- =========================================================
-- 5. PROJECTS
-- Source: controllers/projectController.js
-- =========================================================

-- W10 | WRITE | Create a project.
-- $1 = owner id
-- $2 = project name
-- $3 = description (JSON text containing summary, solution, goals, location)
-- $4 = problem statement
-- $5 = industry/category
-- $6 = project stage
-- $7 = collaboration type/location
-- $8 = expected commitment
INSERT INTO projects (
    owner_id,
    project_name,
    description,
    problem_statement,
    industry,
    project_stage,
    collaboration_type,
    expected_commitment
)
VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
RETURNING id;

-- W11 | WRITE | Add the project owner as the Founder in the project team.
-- $1 = project id; $2 = owner/user id; $3 = role name ('Founder')
INSERT INTO project_members (project_id, user_id, role_name)
VALUES ($1, $2, $3)
ON CONFLICT (project_id, user_id) DO NOTHING;

-- W12 | WRITE | Insert a required skill if it does not exist and return its id.
-- Used once for each skill while creating a project.
-- $1 = skill name
INSERT INTO skills (name)
VALUES ($1)
ON CONFLICT (name)
DO UPDATE SET name = EXCLUDED.name
RETURNING id;

-- W13 | WRITE | Link a required skill to the project.
-- $1 = project id; $2 = skill id
INSERT INTO project_skills (project_id, skill_id)
VALUES ($1, $2)
ON CONFLICT (project_id, skill_id) DO NOTHING;

-- W14 | WRITE | Add a required role to the project.
-- $1 = project id; $2 = role name; $3 = number of openings
INSERT INTO project_roles (
    project_id,
    role_name,
    required_members
)
VALUES ($1, $2, $3);

-- R9 | READ | Common project listing query.
-- The backend appends one of the two WHERE clauses shown in R10 and R11.
-- It returns project details, required skills, roles, total openings
-- and current team-member count.
SELECT
    p.id,
    p.owner_id,
    p.project_name,
    p.description,
    p.industry,
    p.project_stage,
    p.collaboration_type,
    p.expected_commitment,
    p.created_at,
    pr.full_name AS founder_name,
    COALESCE(
        (
            SELECT json_agg(s.name ORDER BY s.name)
            FROM project_skills ps
            JOIN skills s ON s.id = ps.skill_id
            WHERE ps.project_id = p.id
        ),
        '[]'::json
    ) AS skills,
    COALESCE(
        (
            SELECT json_agg(
                json_build_object(
                    'id', r.id,
                    'title', r.role_name,
                    'openings', r.required_members
                )
                ORDER BY r.id
            )
            FROM project_roles r
            WHERE r.project_id = p.id
        ),
        '[]'::json
    ) AS roles,
    COALESCE(
        (
            SELECT SUM(r.required_members)
            FROM project_roles r
            WHERE r.project_id = p.id
        ),
        0
    ) AS required_members,
    (
        SELECT COUNT(*)
        FROM project_members pm
        WHERE pm.project_id = p.id
    ) AS member_count
FROM projects p
LEFT JOIN profiles pr ON pr.user_id = p.owner_id;



