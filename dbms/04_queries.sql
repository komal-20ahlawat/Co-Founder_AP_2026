-- These statements are taken from the current backend controllers:
-- authController.js, profileController.js, skillController.js,
-- interestController.js and projectController.js.
--
-- The backend uses node-postgres (pg Pool/client) with parameterized SQL.
-- $1, $2, ... are values supplied by the backend; this file is a reference
-- for the queries used by the application, not a single script to run at once.
