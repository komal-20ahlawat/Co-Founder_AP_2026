-- =========================================================
-- 1. AUTHENTICATION
-- Source: controllers/authController.js
-- =========================================================

-- R1 | READ | Check whether an email is already registered (signup).
SELECT id
FROM users
WHERE email = $1;

-- W1 | WRITE | Create the user account.
-- $1 = normalized email
-- $2 = password hash generated by bcrypt in the backend
INSERT INTO users (email, password_hash)
VALUES ($1, $2)
RETURNING id, email, created_at;

-- W2 | WRITE | Create the user's initial profile after signup.
-- $1 = newly created user id
-- $2 = user's name
INSERT INTO profiles (user_id, full_name)
VALUES ($1, $2);

-- R2 | READ | Fetch account details for login.
-- The backend compares the submitted password with password_hash using bcrypt.
SELECT
    u.id,
    u.email,
    u.password_hash,
    p.full_name
FROM users u
JOIN profiles p ON u.id = p.user_id
WHERE u.email = $1;

-- R3 | READ | Fetch the logged-in user's details (/auth/me).
-- $1 = authenticated user's id from the JWT
SELECT
    u.id,
    u.email,
    u.email_verified,
    p.full_name,
    p.profile_picture,
    p.headline,
    p.bio,
    p.education,
    p.experience,
    p.github_url,
    p.portfolio_url,
    p.availability,
    p.collaboration_preferences
FROM users u
JOIN profiles p ON u.id = p.user_id
WHERE u.id = $1;


-- =========================================================
-- 2. USER PROFILE
-- Source: controllers/profileController.js
-- =========================================================

-- R4 | READ | Get the logged-in user's profile.
-- $1 = authenticated user's id
SELECT
    u.id,
    u.email,
    p.full_name,
    p.profile_picture,
    p.headline,
    p.bio,
    p.education,
    p.experience,
    p.github_url,
    p.portfolio_url,
    p.availability,
    p.collaboration_preferences
FROM users u
JOIN profiles p ON u.id = p.user_id
WHERE u.id = $1;

-- W3 | WRITE | Update the logged-in user's profile.
-- $1-$8 = profile fields; $9 = authenticated user's id
UPDATE profiles
SET
    full_name = $1,
    headline = $2,
    bio = $3,
    education = $4,
    experience = $5,
    github_url = $6,
    portfolio_url = $7,
    availability = $8,
    updated_at = CURRENT_TIMESTAMP
WHERE user_id = $9
RETURNING *;


-- =========================================================
-- 3. SKILLS
-- Source: controllers/skillController.js
-- =========================================================

-- R5 | READ | Get all available skills.
SELECT id, name
FROM skills
ORDER BY name ASC;

-- R6 | READ | Get skills selected by the logged-in user.
-- $1 = authenticated user's id
SELECT s.id, s.name
FROM skills s
JOIN user_skills us ON s.id = us.skill_id
WHERE us.user_id = $1
ORDER BY s.name ASC;

-- W4 | WRITE | Insert a skill if it does not exist, or return the existing skill.
-- $1 = skill name
INSERT INTO skills (name)
VALUES ($1)
ON CONFLICT (name)
DO UPDATE SET name = EXCLUDED.name
RETURNING id, name;

-- W5 | WRITE | Link the skill to the logged-in user.
-- $1 = user id; $2 = skill id
INSERT INTO user_skills (user_id, skill_id)
VALUES ($1, $2)
ON CONFLICT (user_id, skill_id) DO NOTHING;

-- W6 | WRITE | Remove a skill from the logged-in user's profile.
-- $1 = user id; $2 = skill id
DELETE FROM user_skills
WHERE user_id = $1 AND skill_id = $2
RETURNING skill_id;